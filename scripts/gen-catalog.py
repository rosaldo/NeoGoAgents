"""Generate CATALOG.md from agent frontmatter. Run: uvx python scripts/gen-catalog.py.

Level 1 is the 18-division index; level 2 is a short per-division roster.
The frontmatter is the only source of names and descriptions. Deterministic:
two runs produce byte-identical output.
"""
from pathlib import Path
import json, re

ROOT = Path(__file__).resolve().parent.parent
DIVISIONS = json.loads((ROOT / 'divisions.json').read_text(encoding='utf-8'))['divisions']
OUT = ROOT / 'CATALOG.md'

EXCLUDE = {'integrations', 'skills', 'scripts', 'quant-engine', 'dist', 'strategy', 'examples', '.claude'}


def frontmatter(path):
    text = path.read_text(encoding='utf-8')
    if not text.startswith('---\n'):
        return None
    end = text.find('\n---\n', 4)
    if end < 0:
        return None
    fm = text[4:end]
    desc = re.search(r'^description:[ \t]*(.*)$', fm, re.M)
    return desc.group(1).strip() if desc else None


agents = {}
for division in DIVISIONS:
    found = []
    for f in sorted((ROOT / division).rglob('*.md')):
        if any(p in EXCLUDE for p in f.parts):
            continue
        if f.name.endswith('.reference.md'):
            continue
        desc = frontmatter(f)
        if desc:
            found.append((f.stem, desc))
    agents[division] = sorted(found)

lines = [
    '<!-- Generated by scripts/gen-catalog.py — do not edit by hand. -->',
    '# Agent catalog',
    '',
    'Level 1: the 18 divisions. Read this index first, then only the relevant section below.',
    'Level 2: the agents in that division, with the short frontmatter description.',
    '',
    '## Level 1 — divisions',
    '',
    '| Division | Agents |',
    '|---|---:|',
]
for division, meta in DIVISIONS.items():
    label = meta['label']
    anchor = label.lower().replace(' ', '-')
    lines.append(f'| [{label}](#{anchor}) | {len(agents[division])} |')

for division, meta in DIVISIONS.items():
    lines += ['', f"## {meta['label']}", '']
    for slug, desc in agents[division]:
        lines.append(f'- `{slug}` — {desc}')

OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'wrote {OUT}: {len(DIVISIONS)} divisions, {sum(len(v) for v in agents.values())} agents')
